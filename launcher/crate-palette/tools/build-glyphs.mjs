// Writes lib/glyphs.js from icons/solar-launcher.json (Solar line-duotone, 480 Design,
// CC BY 4.0, vendored with icons/solar_export_perf.mjs). Re-run after re-exporting:
//   node launcher/crate-palette/tools/build-glyphs.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const src = JSON.parse(readFileSync(path.join(here, "..", "..", "..", "icons", "solar-launcher.json"), "utf8"));
const icons = {};
for (const [name, markup] of Object.entries(src.icons)) {
  icons[name] = markup
    .replace(/ style="opacity:var\(--solar-secondary-opacity, 0\.5\)"/g, ' opacity="0.5"')
    .replace(/^<svg /, '<svg stroke-width="1.5" ');
}
const out = `.pragma library

// Generated by tools/build-glyphs.mjs from icons/solar-launcher.json: Solar
// line-duotone icons by 480 Design, CC BY 4.0. Do not edit by hand.

var ICONS = ${JSON.stringify(icons, null, 4)};

function names() {
    return Object.keys(ICONS);
}

// The glyph's SVG with its strokes in one colour ("#rrggbb" or "#aarrggbb").
function svg(name, color) {
    var markup = ICONS[name];
    if (!markup || !/^#([0-9a-fA-F]{6}|[0-9a-fA-F]{8})$/.test(String(color)))
        return "";
    return markup.replace(/currentColor/g, String(color));
}
`;
writeFileSync(path.join(here, "..", "lib", "glyphs.js"), out);
console.log(`wrote ${Object.keys(icons).length} glyphs`);
